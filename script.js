function pickStudent() {
  const input =
    document.getElementById("studentNames");

  if (!input) return;

  const raw = input.value.trim();

  if (!raw) {
    document.getElementById("studentResult")
      .textContent =
      "Алдымен студенттердің есімдерін енгізіңдер.";

    return;
  }

  if (raw !== studentNamesText) {
    studentNamesText = raw;

    availableStudents = raw
      .split(/[,;\n]+/)
      .map(name => name.trim())
      .filter(Boolean);
  }

  if (availableStudents.length === 0) {
    availableStudents = studentNamesText
      .split(/[,;\n]+/)
      .map(name => name.trim())
      .filter(Boolean);
  }

  if (availableStudents.length === 0) return;

  const randomIndex = Math.floor(
    Math.random() * availableStudents.length
  );

  const selected = availableStudents.splice(
    randomIndex,
    1
  )[0];

  document.getElementById("studentResult")
    .textContent =
    "Таңдалған студент: " + selected;
}

