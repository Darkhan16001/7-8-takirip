function renderFallbackSlides() {
  const container =
    document.getElementById("videoContainer");

  if (!container) return;

  container.innerHTML = fallbackSlideHTML();

  const status = document.getElementById("videoStatus");

  if (status) {
    status.textContent =
      "Интерактивті түсіндірме ашылды.";
  }
}

function changeSlide(direction) {
  currentSlide += direction;

  if (currentSlide < 0) {
    currentSlide = videoSlides.length - 1;
  }

  if (currentSlide >= videoSlides.length) {
    currentSlide = 0;
  }

  renderFallbackSlides();
}

