const STORAGE_KEY = "darkhan-history-7-8-scores";

let awarded = [{}, {}, {}];

try {
  const saved = JSON.parse(
    localStorage.getItem(STORAGE_KEY)
  );

  if (
    Array.isArray(saved) &&
    saved.length === 3 &&
    saved.every(
      item =>
        item !== null &&
        typeof item === "object" &&
        !Array.isArray(item)
    )
  ) {
    awarded = saved;
  }
} catch (error) {
  awarded = [{}, {}, {}];
}

function saveScores() {
  try {
    localStorage.setItem(
      STORAGE_KEY,
      JSON.stringify(awarded)
    );
  } catch (error) {
    // Сақтау мүмкін болмаса,
    // сабақ жұмысы жалғасады.
  }
}

function teamScore(index) {
  return Object.values(awarded[index]).reduce(
    (sum, points) =>
      sum + (Number.isFinite(points) ? points : 0),
    0
  );
}

function updateScoreboard() {
  document.getElementById("scoreboard").innerHTML =
    awarded.map((_, index) => `
      <div class="score-row">
        <span>${index + 1}-команда</span>

        <strong>
          ${teamScore(index)} ұпай
        </strong>
      </div>
    `).join("");

  if (currentStage === 7) {
    renderFinalScores();
  }
}

function awardButton(team, key, points) {
  const active = Boolean(awarded[team][key]);

  return `
    <button
      class="award ${active ? "active" : ""}"
      data-award="${team}|${key}|${points}"
    >
      ${active ? "✓ Ұпай берілді" : "+" + points + " ұпай"}
    </button>
  `;
}

function refreshAwardButtons() {
  document.querySelectorAll("[data-award]")
    .forEach(button => {
      const [team, key, points] =
        button.dataset.award.split("|");

      const active = Boolean(
        awarded[Number(team)][key]
      );

      button.classList.toggle("active", active);

      button.textContent = active
        ? "✓ Ұпай берілді"
        : "+" + points + " ұпай";
    });
}

function toggleAward(team, key, points) {
  if (!awarded[team]) return;

  if (awarded[team][key]) {
    delete awarded[team][key];
  } else {
    awarded[team][key] = points;
  }

  saveScores();
  refreshAwardButtons();
  updateScoreboard();
}

function resetScores() {
  if (!confirm("Барлық команданың ұпайын нөлдейміз бе?")) {
    return;
  }

  awarded = [{}, {}, {}];

  saveScores();
  refreshAwardButtons();
  updateScoreboard();
}

document.getElementById("resetScores")
  .addEventListener("click", resetScores);

