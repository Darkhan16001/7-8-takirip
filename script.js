// 20. БАТЫРМАЛАРДЫ БАСҚАРУ
// =============================================

document.addEventListener("click", function(event) {

  // Сабақ кезеңін ауыстыру

  const stageButton =
    event.target.closest("[data-stage]");

  if (stageButton) {
    showPage(
      Number(stageButton.dataset.stage)
    );

    return;
  }

  // Жауапты көрсету / жасыру

  const revealButton =
    event.target.closest("[data-reveal]");

  if (revealButton) {
    const answerID =
      revealButton.dataset.reveal;

    const answer =
      document.getElementById(answerID);

    if (!answer) return;

    answer.classList.toggle("visible");

    revealButton.textContent =
      answer.classList.contains("visible")
        ? "Жауапты жасыру"
        : "Жауабын көрсету";

    return;
  }

  // Ұпай беру / қайтарып алу

  const awardControl =
    event.target.closest("[data-award]");

  if (awardControl) {
    const [team, key, points] =
      awardControl.dataset.award.split("|");

    toggleAward(
      Number(team),
      key,
      Number(points)
    );

    return;
  }

  // Студентті кездейсоқ таңдау

  if (event.target.closest("#pickStudent")) {
    pickStudent();
    return;
  }

  // 1 немесе 2 видеоны таңдау

  const videoButton =
    event.target.closest("[data-video]");

  if (videoButton) {
    currentVideo =
      Number(videoButton.dataset.video);

    renderVideoPlayer();
    return;
  }

  // Видео мен түсіндірме арасында ауысу

  const modeButton =
    event.target.closest("[data-video-mode]");

  if (modeButton) {
    const mode =
      modeButton.dataset.videoMode;

    if (mode === "slides") {
      currentSlide = 0;
      renderFallbackSlides();
    }

    if (mode === "player") {
      renderVideoPlayer();
    }

    return;
  }

  // Интерактивті түсіндірменің слайдтары

  const slideButton =
    event.target.closest("[data-slide]");

  if (slideButton) {
    changeSlide(
      Number(slideButton.dataset.slide)
    );

    return;
  }
});

