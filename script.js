function showPage(index) {
  if (index < 0 || index >= pages.length) {
    return;
  }

  currentStage = index;

  // Бет ауысқанда бұрынғы видео
  // DOM-нан алынып, ойнатылуы тоқтайды.

  document.getElementById("content").innerHTML =
    pages[index]();

  document.getElementById("currentStageName").textContent =
    stages[index].name;

  document.getElementById("pageNumber").textContent =
    `${index + 1} / ${pages.length}`;

  document.getElementById("progressBar").style.width =
    ((index + 1) / pages.length * 100) + "%";

  const previous =
    document.getElementById("previousBtn");

  const next =
    document.getElementById("nextBtn");

  previous.disabled = index === 0;

  next.disabled = index === pages.length - 1;

  next.textContent =
    index === pages.length - 2
      ? "Қорытындыға өту →"
      : "Келесі бет →";

  renderNavigation();

  if (index === 3) {
    renderVideoPlayer();
  }

  if (index === 5) {
    const input =
      document.getElementById("studentNames");

    if (input) {
      input.value = studentNamesText;
    }
  }

  if (index === 6) {
    refreshAwardButtons();
  }

  if (index === 7) {
    renderFinalScores();
  }

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

